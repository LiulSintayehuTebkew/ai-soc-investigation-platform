def normalize_alert(item):
    alert = item.get("alert", {})
    return {
        "title": alert.get("search_name") or alert.get("rule_name") or alert.get("sid") or "Unknown Alert",
        "ip": alert.get("src_ip") or alert.get("Source_Network_Address") or "N/A",
        "user": str(alert.get("user") or alert.get("Account_Name") or "N/A"),
        "severity": alert.get("severity") or "Unknown",
        "analysis": item.get("analysis", "No analysis available."),
        "raw": item
    }

def normalize_alerts(alerts):
    return [normalize_alert(x) for x in alerts]


def build_incident_report(alert):

    title = alert.get(
        "title",
        "Unknown Investigation"
    )

    ip = alert.get(
        "ip",
        "N/A"
    )

    user = alert.get(
        "user",
        "N/A"
    )

    analysis = alert.get(
        "analysis",
        "No analysis available."
    )

    return f"""
# Incident Report

## Investigation

{title}

## Source IP

{ip}

## User

{user}

## Analysis

{analysis}

## Generated By

AI SOC Investigator
"""